export const USAGE_NOTICE_EN = `[Read this before asking]

■ How to ask

What you can ask
  What is the story of Haibane Renmei?
  Who is Ainz Ooal Gown?
  What's the opening song of Bocchi the Rock?
  Which characters has Hanazawa Kana voiced recently?
  Any anime where the protagonist is overpowered but keeps a low profile?
    (describe it — you don't need to remember the title)
  ── Seasonal lineups come straight from the database, no AI needed ──
  What anime was airing this season ten years ago?

How your question is handled
  The system works in Chinese. Your question is machine-translated into
  Chinese, answered from Chinese sources, and the answer is translated
  back into English. Titles and names are kept exactly as you typed them,
  because a wrong guess at a Chinese title would point to a different show.

If you get no result, rephrase
  · Use the full official title, English or romanized Japanese
    (Steins;Gate, Shingeki no Kyojin). Very long titles may not be
    recognized — try a shorter official form.
  · Write Japanese names family name first: "Hanazawa Kana",
    not "Kana Hanazawa" — the database only stores that order.
  · If the system asks "which one did you mean?", there are several shows
    with the same title (for example two versions of Dororo). Pick one.

■ Please note

Story questions take 10–50 seconds
  Each question is translated, then the system searches its sources,
  re-ranks them and writes an answer, which is then translated back.
  Most of the time goes into writing the answer.
  Voice actor questions take about 5–15 seconds.

Answers may contain spoilers
  We filter out content that Moegirlpedia marks as a spoiler
  (currently 19,381 passages), but this filter will always miss some —
  unmarked spoilers can't be detected. If you want to avoid spoilers,
  don't ask about endings.

Answers may be wrong — check the sources
  "Sources" lists the passages the answer was actually based on.
  They are in Chinese (from Moegirlpedia and Bangumi). Be careful when the
  answer contains details that aren't in the sources: the model may be
  "remembering" them rather than reading them. Translation can also
  introduce mistakes, especially in character names.

No answer ≠ the show isn't here
  We cover 11,453 anime; 79.3% of them have plot sources
  (97.3% weighted by viewers). Niche titles often only have basic info.
  Endings are the hardest: many are only described on character pages,
  which aren't fully collected yet. In that case the system tells you how
  far its sources go instead of making up an ending.

What it can't do yet
  · Anime that haven't aired yet — data goes up to 2026-09-11
  · Questions unrelated to anime — the system checks first, and asks you
    to be more specific when it isn't sure

──────────────────────────────────────────────
Sources: Moegirlpedia (CC BY-NC-SA 3.0) and Bangumi.
Answers are generated by AI from these sources and machine-translated.`
